from fastapi import APIRouter, Depends, HTTPException
from sqlalchemy.orm import Session
from sqlalchemy import select
from app.db.database import get_db
from app.models.database_models import Flag, Metric, Report, Company
from app.schemas.api_schemas import FlagOut
from app.services.evidence_service import evidence_payload
from app.services.explainability_service import model_explanation, mitigation_recommendations

router = APIRouter(prefix="/flags", tags=["flags"])


@router.get("", response_model=list[FlagOut])
def flags(db: Session = Depends(get_db)):
    stmt = select(Flag).order_by(Flag.id.desc()).limit(1000)
    return list(db.scalars(stmt).all())


@router.get("/{flag_id}", response_model=FlagOut)
def flag(flag_id: int, db: Session = Depends(get_db)):
    item = db.get(Flag, flag_id)
    if not item:
        raise HTTPException(404, "Flag not found")
    return item


@router.get("/{flag_id}/evidence")
def evidence(flag_id: int, db: Session = Depends(get_db)):
    flag_item = db.get(Flag, flag_id)
    if not flag_item:
        raise HTTPException(404, "Flag not found")
    metrics = list(db.scalars(select(Metric).where(Metric.report_id == flag_item.report_id)).all())
    report = db.get(Report, flag_item.report_id)
    company = db.get(Company, report.company_id) if report else None
    return {"flag": flag_item.__dict__, "company": company.name if company else "Unknown", "report": report.__dict__ if report else {}, "evidence": evidence_payload(flag_item, metrics)["evidence"]}


@router.get("/{flag_id}/explanation")
def explanation(flag_id: int, db: Session = Depends(get_db)):
    flag_item = db.get(Flag, flag_id)
    if not flag_item:
        raise HTTPException(404, "Flag not found")

    model = model_explanation(db, flag_item.report_id) if flag_item.flag_type == "ML_ANOMALY" else {
        "available": False,
        "method": "Rule-based validation",
        "features": [],
        "note": "This flag was generated by a deterministic validation rule. SHAP is not required for the rule result; the triggered check and source evidence explain the signal."
    }
    mitigation = mitigation_recommendations(flag_item, model)

    triggered = [{
        "name": flag_item.flag_type.replace("_", " ").title(),
        "status": "TRIGGERED",
        "detail": flag_item.description,
    }]

    return {
        "flag_id": flag_id,
        "rule_explanation": flag_item.description,
        "triggered_checks": triggered,
        "model_explanation": model,
        "mitigation": mitigation,
        "note": "Model contributions describe the fitted anomaly detector's local feature behavior; they are not probabilities and do not establish wrongdoing."
    }


@router.get("/{flag_id}/mitigation")
def mitigation(flag_id: int, db: Session = Depends(get_db)):
    flag_item = db.get(Flag, flag_id)
    if not flag_item:
        raise HTTPException(404, "Flag not found")
    model = model_explanation(db, flag_item.report_id) if flag_item.flag_type == "ML_ANOMALY" else None
    return mitigation_recommendations(flag_item, model)
